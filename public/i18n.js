let lang = "ja";
export const getLang = () => lang;
export function setLang(l) {
  if (LANGS.includes(l)) lang = l;
  return lang;
}

// The browser's preferred languages -> "ja" or "en" (the first one we support; English otherwise)
export function detectLang(languages) {
  for (const l of languages ?? []) {
    const base = String(l).toLowerCase().split("-")[0];
    if (LANGS.includes(base)) return base;
  }
  return "en";
}

// Text for a key with {placeholders} filled in. Falls back to Japanese, then to the key itself
export function t(key, vars = {}) {
  const s = STRINGS[lang][key] ?? STRINGS.ja[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

// Fill static page text: data-i18n (text), data-i18n-placeholder, data-i18n-aria (aria-label)
export function applyI18n(root) {
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-placeholder]")) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of root.querySelectorAll("[data-i18n-aria]")) el.setAttribute("aria-label", t(el.dataset.i18nAria));
  if (root.documentElement) root.documentElement.lang = lang;
}
