// Rotate a part 90 degrees clockwise `times` times; optionally mirror left-right first
export function transform(rows: string[], times: number, flip = false): string[] {
  let g = rows.map((r) => [...(flip ? [...r].reverse().join("") : r)]);
  for (let t = 0; t < ((times % 4) + 4) % 4; t++) {
    const n = g.length;
    g = Array.from({ length: n }, (_, y) => Array.from({ length: n }, (_, x) => g[n - 1 - x][y]));
  }
  return g.map((r) => r.join(""));
}
